#!/usr/bin/env python3
"""Create a traditional IPS patch against a verified Pokémon Crystal (US 1.1).

Requires only built ROMs generated by the open-source disassemblies.
Never commits, publishes, or embeds either complete copyrighted ROM.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path


def sha256(blob: bytes) -> str:
    return hashlib.sha256(blob).hexdigest()


def make_ips(original: bytes, changed: bytes) -> bytes:
    if len(changed) > 0xFFFFFF:
        raise ValueError("Target ROM too large for IPS patch format")
    patch = bytearray(b"PATCH")
    i = 0
    while i < len(changed):
        old = original[i] if i < len(original) else -1
        if changed[i] == old:
            i += 1
            continue
        start = i
        while i < len(changed) and i - start < 65535:
            previous = original[i] if i < len(original) else -1
            if changed[i] == previous:
                break
            i += 1
        if start == 0x454F46:
            # That is the IPS 'EOF' magic; fold this byte into the prior record
            # rather than emit an ambiguous record location.
            raise ValueError("IPS hunk starts at reserved offset 0x454F46")
        patch.extend(start.to_bytes(3, "big"))
        patch.extend((i - start).to_bytes(2, "big"))
        patch.extend(changed[start:i])
    patch.extend(b"EOF")
    if len(changed) != len(original):
        patch.extend(len(changed).to_bytes(3, "big"))
    return bytes(patch)


def apply_ips(original: bytes, patch: bytes) -> bytes:
    if not patch.startswith(b"PATCH"):
        raise ValueError("Bad IPS header")
    output = bytearray(original)
    i = 5
    while patch[i:i+3] != b"EOF":
        if len(patch) - i < 5:
            raise ValueError("Truncated patch record")
        offset = int.from_bytes(patch[i:i+3], "big")
        size = int.from_bytes(patch[i+3:i+5], "big")
        i += 5
        if size == 0:
            count = int.from_bytes(patch[i:i+2], "big")
            block = patch[i+2:i+3] * count
            i += 3
        else:
            block = patch[i:i+size]
            if len(block) != size:
                raise ValueError("Truncated patch data")
            i += size
        if offset + len(block) > len(output):
            output.extend(b"\0" * (offset + len(block) - len(output)))
        output[offset:offset+len(block)] = block
    end = i + 3
    if len(patch) == end + 3:
        target_size = int.from_bytes(patch[end:end+3], "big")
        del output[target_size:]
    elif len(patch) != end:
        raise ValueError("Unexpected bytes after IPS EOF")
    return bytes(output)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("original", type=Path)
    parser.add_argument("translated", type=Path)
    parser.add_argument("--output", type=Path, default=Path("Crystal_Traditional_Chinese_v1.1.ips"))
    parser.add_argument("--report", type=Path, default=Path("zh_tw_patch_manifest.json"))
    args = parser.parse_args()
    old = args.original.read_bytes()
    new = args.translated.read_bytes()
    base_sha1 = hashlib.sha1(old).hexdigest()
    expected_sha1 = "f2f52230b536214ef7c9924f483392993e226cfb"
    if base_sha1 != expected_sha1:
        raise ValueError(f"Source ROM checksum mismatch: {base_sha1}; expected {expected_sha1}")
    patch = make_ips(old, new)
    if apply_ips(old, patch) != new:
        raise AssertionError("IPS round-trip failed")
    args.output.write_bytes(patch)
    report = {
        "format": "IPS",
        "base": "Pokemon Crystal (US) v1.1",
        "base_sha1": base_sha1,
        "base_sha256": sha256(old),
        "patch_file": args.output.name,
        "patch_sha256": sha256(patch),
        "patch_bytes": len(patch),
        "result_sha256": sha256(new),
        "result_bytes": len(new),
        "verification": "IPS patch applied to the original, output matched translated ROM byte-for-byte",
        "qualification": "Only a translation and smoke-test candidate until full gameplay QA",
    }
    args.report.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(report, ensure_ascii=False))


if __name__ == "__main__":
    main()
